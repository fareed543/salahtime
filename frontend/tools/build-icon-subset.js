// Writes src/styles/bootstrap-icons-subset.css: the Bootstrap Icons font rules for only the icons
// SalahTime uses (PERF-05). The full bootstrap-icons.css has ~2,000 icon rules (~100 KB) and every
// visitor downloaded it as part of styles.css.
//
// Icons are found as "bi-<name>" in src/app, src/index.html, src/styles, src/assets/**/*.json and
// tools/prerender-seo.js. Every icon in this app is written out like that (also in data files and
// [ngClass] bindings); an icon name built at runtime ('bi-' + x) would not be found, so the script
// fails if it sees one.
//
// Runs on prebuild. The output is committed so `ng serve` works without a prebuild.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const iconCssPath = path.join(root, 'node_modules/bootstrap-icons/font/bootstrap-icons.css');
const outPath = path.join(root, 'src/styles/bootstrap-icons-subset.css');

const files = [];
const walk = (dir, pattern) => {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, pattern);
    else if (pattern.test(entry.name) && !/\.spec\.ts$/.test(entry.name)) files.push(full);
  }
};
walk(path.join(root, 'src/app'), /\.(html|ts|scss)$/);
walk(path.join(root, 'src/styles'), /\.scss$/);
walk(path.join(root, 'src/assets'), /\.json$/);
files.push(path.join(root, 'src/index.html'), path.join(root, 'tools/prerender-seo.js'));
const sources = files.filter(file => fs.existsSync(file)).map(file => fs.readFileSync(file, 'utf8')).join('\n');

const dynamic = sources.match(/['"`]bi-['"`]\s*\+|`bi-\$\{/);
if (dynamic) {
  console.error(`build-icon-subset: an icon class is built at runtime (${dynamic[0]}); list the icons literally instead.`);
  process.exit(1);
}

const iconCss = fs.readFileSync(iconCssPath, 'utf8');
const available = new Map([...iconCss.matchAll(/^\.bi-([a-z0-9-]+)::before \{ content: "(\\[0-9a-f]+)"; \}$/gm)]
  .map(m => [m[1], m[2]]));
const used = [...new Set([...sources.matchAll(/\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)/g)].map(m => m[1]))]
  .filter(name => available.has(name))
  .sort();

const fontFace = iconCss.match(/@font-face\s*\{[^}]*\}/)[0]
  // Point at the package's font files; the Angular build copies them next to styles.css.
  .replace(/url\("\.\/fonts\//g, 'url("../../node_modules/bootstrap-icons/font/fonts/');
const base = iconCss.match(/\.bi::before,[^{]*\{[^}]*\}/)[0];

const css = [
  `/* Generated by tools/build-icon-subset.js from bootstrap-icons ${require(path.join(root, 'node_modules/bootstrap-icons/package.json')).version}: ${used.length} icons used by the app. Do not edit. */`,
  fontFace,
  base,
  ...used.map(name => `.bi-${name}::before { content: "${available.get(name)}"; }`),
  ''
].join('\n');

const previous = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
if (previous !== css) fs.writeFileSync(outPath, css, 'utf8');
console.log(`Icon subset: ${used.length} of ${available.size} Bootstrap Icons -> ${path.relative(root, outPath)} (${(css.length / 1024).toFixed(1)} KB)`);
